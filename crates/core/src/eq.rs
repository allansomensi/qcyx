#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn set_preset_matches_capture_for_every_preset() {
        for preset in [
            EqPreset::Spatial,
            EqPreset::Default,
            EqPreset::Popular,
            EqPreset::BassBoost,
            EqPreset::Rock,
            EqPreset::Soft,
            EqPreset::Classic,
        ] {
            let cmd = set_preset(preset);
            assert_eq!(cmd.parameters[0], preset.id());
            assert_eq!(&cmd.parameters[1..], preset.table());
            assert_eq!(cmd.parameters.len(), 143);
        }
    }

    #[test]
    fn default_and_spatial_share_the_same_table() {
        assert_eq!(EqPreset::Default.table(), EqPreset::Spatial.table());
        assert_ne!(EqPreset::Default.id(), EqPreset::Spatial.id());
    }

    #[test]
    fn every_preset_id_is_distinct() {
        let ids = [
            EqPreset::Spatial.id(),
            EqPreset::Default.id(),
            EqPreset::Popular.id(),
            EqPreset::BassBoost.id(),
            EqPreset::Rock.id(),
            EqPreset::Soft.id(),
            EqPreset::Classic.id(),
        ];
        for (i, a) in ids.iter().enumerate() {
            for b in &ids[i + 1..] {
                assert_ne!(a, b);
            }
        }
        for id in ids {
            assert_ne!(id, CUSTOM_PRESET_ID);
        }
    }
}
