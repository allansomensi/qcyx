//! Equalizer presets, written to characteristic `00001001` (opcode `0x22`, `0xFF`-framed).
//!
//! Confirmed by direct capture: selecting a built-in preset sends the entire
//! 142-byte band/filter table over the wire, tagged with a 1-byte preset ID.

use crate::protocol::Command;

/// Opcode for equalizer preset/table selection.
pub const OPCODE: u8 = 0x22;

/// Preset ID tag used when custom (per-band) editing is active.
pub const CUSTOM_PRESET_ID: u8 = 0x80;

/// A built-in equalizer preset.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EqPreset {
    Spatial,
    Default,
    Popular,
    BassBoost,
    Rock,
    Soft,
    Classic,
}

impl EqPreset {
    /// This preset's 1-byte ID.
    pub const fn id(self) -> u8 {
        match self {
            EqPreset::Spatial => 0x0a,
            EqPreset::Default => 0x01,
            EqPreset::Popular => 0x02,
            EqPreset::BassBoost => 0x03,
            EqPreset::Rock => 0x04,
            EqPreset::Soft => 0x05,
            EqPreset::Classic => 0x06,
        }
    }

    /// This preset's full 142-byte band/filter table.
    pub fn table(self) -> &'static [u8] {
        match self {
            EqPreset::Spatial => &table::SPATIAL,
            EqPreset::Default => &table::DEFAULT,
            EqPreset::Popular => &table::POPULAR,
            EqPreset::BassBoost => &table::BASS_BOOST,
            EqPreset::Rock => &table::ROCK,
            EqPreset::Soft => &table::SOFT,
            EqPreset::Classic => &table::CLASSIC,
        }
    }
}

/// Builds the EQ-preset-select write command.
pub fn set_preset(preset: EqPreset) -> Command {
    let mut parameters = Vec::with_capacity(1 + preset.table().len());
    parameters.push(preset.id());
    parameters.extend_from_slice(preset.table());
    Command::new(OPCODE, parameters)
}

